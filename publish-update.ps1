param(
    [Parameter(Mandatory = $true)]
    [ValidateSet("music", "video", "both")]
    [string]$App,

    [Parameter(Mandatory = $true)]
    [string]$Version,

    [string]$Notes = "Mejoras y correcciones.",

    [switch]$SkipBump,
    [switch]$Install,
    [switch]$Desktop,
    [switch]$SkipLocalInstall
)

$ErrorActionPreference = "Stop"

$repoDir = $PSScriptRoot
$repoSlug = "baninafra/free-media"
$manifestPath = Join-Path $repoDir "updates.json"
$manifest = Get-Content -Raw -Encoding UTF8 $manifestPath | ConvertFrom-Json

$apps = @()
if ($App -eq "music" -or $App -eq "both") {
    $apps += @{
        Key = "freeMusic"
        Name = "Free Music"
        AssetPrefix = "FreeMusic"
        PackageId = "com.celeste.music"
        Dir = "C:\Users\fbani\claude code\Music"
        TagPrefix = "free-music"
        ProcessName = "celeste"
    }
}
if ($App -eq "video" -or $App -eq "both") {
    $apps += @{
        Key = "freeVideo"
        Name = "Free Video"
        AssetPrefix = "FreeVideo"
        PackageId = "com.telechea.video"
        Dir = "C:\Users\fbani\claude code\Telechea"
        TagPrefix = "free-video"
        ProcessName = "telechea"
    }
}

$tagName = if ($App -eq "both") { "v$Version" } else { "$($apps[0].TagPrefix)-v$Version" }
$releaseAssets = @()
$stagingDir = Join-Path $repoDir "dist"
New-Item -ItemType Directory -Force -Path $stagingDir | Out-Null

foreach ($cfg in $apps) {
    Write-Host "`n=== Preparando $($cfg.Name) v$Version ===" -ForegroundColor Cyan

    $propsPath = Join-Path $cfg.Dir "src-tauri\gen\android\app\tauri.properties"
    $propsText = Get-Content -Raw $propsPath
    $currentCode = 1000
    if ($propsText -match "tauri\.android\.versionCode=(\d+)") {
        $currentCode = [int]$Matches[1]
    }
    $nextCode = if ($SkipBump) { $currentCode } else { $currentCode + 1 }

    # Update tauri.properties
    $newProps = "// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.`ntauri.android.versionName=$Version`ntauri.android.versionCode=$nextCode`n"
    [System.IO.File]::WriteAllText($propsPath, $newProps, (New-Object System.Text.UTF8Encoding($false)))

    # Update package.json
    $pkgPath = Join-Path $cfg.Dir "package.json"
    $pkgText = Get-Content -Raw -Encoding UTF8 $pkgPath
    $pkgText = [regex]::Replace($pkgText, '"version"\s*:\s*"[^"]+"', "`"version`": `"$Version`"", 1)
    [System.IO.File]::WriteAllText($pkgPath, $pkgText, (New-Object System.Text.UTF8Encoding($false)))

    # Update tauri.conf.json
    $confPath = Join-Path $cfg.Dir "src-tauri\tauri.conf.json"
    $confText = Get-Content -Raw -Encoding UTF8 $confPath
    $confText = [regex]::Replace($confText, '"version"\s*:\s*"[^"]+"', "`"version`": `"$Version`"", 1)
    [System.IO.File]::WriteAllText($confPath, $confText, (New-Object System.Text.UTF8Encoding($false)))

    Write-Host "Version actualizada: $Version (versionCode: $nextCode)" -ForegroundColor Yellow

    # Build signed Release APK
    Push-Location $cfg.Dir
    try {
        & .\scripts\build-android.ps1 -Release
        if ($LASTEXITCODE -ne 0) { throw "Falló la compilación Android de $($cfg.Name)" }
    } finally {
        Pop-Location
    }

    $apkSrc = Join-Path $cfg.Dir "src-tauri\gen\android\app\build\outputs\apk\arm64\release\app-arm64-release.apk"
    if (!(Test-Path $apkSrc)) {
        throw "No se encontró el APK firmado en: $apkSrc"
    }

    $assetName = "$($cfg.AssetPrefix)-v$Version.apk"
    $assetDest = Join-Path $stagingDir $assetName
    Copy-Item -Force $apkSrc $assetDest
    $releaseAssets += $assetDest

    $apkUrl = "https://github.com/$repoSlug/releases/download/$tagName/$assetName"
    $entry = $manifest.($cfg.Key)
    $entry.appName = $cfg.Name
    $entry.version = $Version
    $entry.versionCode = $nextCode
    $entry.apkUrl = $apkUrl
    $entry.notes = $Notes

    if ($Install) {
        $adb = "$env:LOCALAPPDATA\Android\Sdk\platform-tools\adb.exe"
        Write-Host "Instalando $($cfg.Name) en celular via ADB..." -ForegroundColor Cyan
        & $adb install -r $assetDest
        if ($LASTEXITCODE -eq 0) {
            & $adb shell am start -n "$($cfg.PackageId)/.MainActivity"
        }
    }

    if ($Desktop) {
        Write-Host "Compilando instalador de PC de $($cfg.Name)..." -ForegroundColor Cyan
        Push-Location $cfg.Dir
        try {
            & .\scripts\build-desktop.ps1
            if ($LASTEXITCODE -ne 0) { throw "Falló la compilación de PC de $($cfg.Name)" }
            $setup = Get-ChildItem "src-tauri\target\release\bundle\nsis\*_$($Version)_*-setup.exe" | Sort-Object LastWriteTime -Descending | Select-Object -First 1
            if (!$setup) { throw "No se encontró el instalador NSIS v$Version de $($cfg.Name)" }
        } finally {
            Pop-Location
        }

        # Publicar el instalador para que la app de PC se actualice sola
        $exeName = "$($cfg.AssetPrefix)-v$Version-setup.exe"
        $exeDest = Join-Path $stagingDir $exeName
        Copy-Item -Force $setup.FullName $exeDest
        $releaseAssets += $exeDest
        $exeUrl = "https://github.com/$repoSlug/releases/download/$tagName/$exeName"
        $entry | Add-Member -NotePropertyName exeUrl -NotePropertyValue $exeUrl -Force

        if (!$SkipLocalInstall) {
            Write-Host "Instalando $($cfg.Name) v$Version en esta PC..." -ForegroundColor Cyan
            $installedExe = Join-Path $env:LOCALAPPDATA "$($cfg.Name)\$($cfg.ProcessName).exe"
            $installed = $false
            for ($attempt = 1; $attempt -le 3 -and -not $installed; $attempt++) {
                # Esperar a que la app se cierre de verdad: si el .exe sigue bloqueado el
                # instalador silencioso no lo reemplaza y no avisa.
                $running = Get-Process -Name $cfg.ProcessName -ErrorAction SilentlyContinue
                if ($running) {
                    $running | Stop-Process -Force
                    $running | Wait-Process -Timeout 15 -ErrorAction SilentlyContinue
                }
                Start-Sleep -Seconds 2
                Start-Process -FilePath $exeDest -ArgumentList "/S" -Wait
                if (Test-Path $installedExe) {
                    $installed = ((Get-Item $installedExe).VersionInfo.ProductVersion -eq $Version)
                }
                if (-not $installed) {
                    Write-Warning "Intento $attempt: $($cfg.Name) no quedó en v$Version, reintentando..."
                }
            }
            if (-not $installed) { throw "No se pudo instalar $($cfg.Name) v$Version en esta PC" }

            # El instalador silencioso solo crea el acceso del menú Inicio: agregar el del escritorio
            if (Test-Path $installedExe) {
                $desktopDir = [Environment]::GetFolderPath("Desktop")
                $shell = New-Object -ComObject WScript.Shell
                $lnk = $shell.CreateShortcut((Join-Path $desktopDir "$($cfg.Name).lnk"))
                $lnk.TargetPath = $installedExe
                $lnk.WorkingDirectory = Split-Path $installedExe
                $lnk.IconLocation = "$installedExe,0"
                $lnk.Save()
                Start-Process -FilePath $installedExe
            } else {
                Write-Warning "No se encontró $installedExe después de instalar"
            }
        }
    }
}

Write-Host "`n=== Publicando Release $tagName en GitHub ($repoSlug) ===" -ForegroundColor Cyan
Push-Location $repoDir
try {
    # Save updated updates.json
    $jsonOut = $manifest | ConvertTo-Json -Depth 5
    [System.IO.File]::WriteAllText($manifestPath, "$jsonOut`n", (New-Object System.Text.UTF8Encoding($false)))

    git add updates.json README.md publish-update.ps1 .gitignore
    $hasChanges = git status --porcelain
    if ($hasChanges) {
        git commit -m "Release $tagName"
    }
    git push origin main

    # Check if release tag already exists
    $prevPref = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    $null = gh release view $tagName --repo $repoSlug 2>&1
    $existsCode = $LASTEXITCODE
    $ErrorActionPreference = $prevPref

    if ($existsCode -eq 0) {
        Write-Host "Actualizando assets en release existente $tagName..." -ForegroundColor Yellow
        gh release upload $tagName @releaseAssets --clobber --repo $repoSlug
        gh release edit $tagName --notes $Notes --repo $repoSlug
    } else {
        $title = if ($App -eq "both") { "Free Music & Free Video v$Version" } else { "$($apps[0].Name) v$Version" }
        gh release create $tagName @releaseAssets --title $title --notes $Notes --repo $repoSlug
    }
    if ($LASTEXITCODE -ne 0) { throw "Falló la publicación en GitHub Releases" }
} finally {
    Pop-Location
}

Write-Host "`nActualización publicada con éxito: https://github.com/$repoSlug/releases/tag/$tagName" -ForegroundColor Green
Write-Host "Todos los celulares con la app instalada recibirán el aviso al abrirla." -ForegroundColor Green
